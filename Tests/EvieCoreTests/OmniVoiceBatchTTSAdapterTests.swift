import Darwin
import Foundation
import Testing

@testable import EvieCore

@Suite("OmniVoice batch TTS adapter")
struct OmniVoiceBatchTTSAdapterTests {
  @Test("sends private request content only through stdin and restricts temporary files")
  func privateStandardInputAndPermissions() async throws {
    let fixture = try Fixture(script: Self.successScript)
    defer { fixture.remove() }
    let adapter = try OmniVoiceBatchTTSAdapter(configuration: fixture.configuration())

    let audio = try await adapter.synthesize(fixture.request())
    let requestDirectory = audio.fileURL.deletingLastPathComponent()
    let evieDirectory = fixture.temporaryRootURL.deletingLastPathComponent()

    #expect(try fixture.permissions(at: evieDirectory) == 0o700)
    #expect(try fixture.permissions(at: fixture.temporaryRootURL) == 0o700)
    #expect(try fixture.permissions(at: requestDirectory) == 0o700)
    #expect(try fixture.permissions(at: audio.fileURL) == 0o600)
    let output = try Data(contentsOf: audio.fileURL)
    #expect(output.count == 46)
    #expect(output.prefix(4) == Data("RIFF".utf8))
    #expect(output[8..<12] == Data("WAVE".utf8))

    let names = try Set(
      FileManager.default.contentsOfDirectory(
        at: requestDirectory,
        includingPropertiesForKeys: nil
      ).map(\.lastPathComponent)
    )
    #expect(names == ["cache", "speech.wav"])

    audio.discard()
    #expect(!FileManager.default.fileExists(atPath: requestDirectory.path))
  }

  @Test("treats a successful exit without generated bytes as a failure and cleans up")
  func missingOutput() async throws {
    let fixture = try Fixture(script: Self.emptyOutputScript)
    defer { fixture.remove() }
    let adapter = try OmniVoiceBatchTTSAdapter(configuration: fixture.configuration())

    do {
      _ = try await adapter.synthesize(fixture.request())
      Issue.record("Expected an output validation failure.")
    } catch let error as EvieTTSError {
      #expect(error == .outputMissing)
    }

    #expect(try fixture.requestDirectories().isEmpty)
  }

  @Test("rejects a non-WAV output and cleans it up")
  func nonWaveOutput() async throws {
    let fixture = try Fixture(script: Self.nonWaveOutputScript)
    defer { fixture.remove() }
    let adapter = try OmniVoiceBatchTTSAdapter(configuration: fixture.configuration())

    do {
      _ = try await adapter.synthesize(fixture.request())
      Issue.record("Expected a WAV validation failure.")
    } catch let error as EvieTTSError {
      #expect(error == .outputMissing)
    }

    #expect(try fixture.requestDirectories().isEmpty)
  }

  @Test("rejects an oversized output before returning it")
  func oversizedOutput() async throws {
    let fixture = try Fixture(script: Self.oversizedOutputScript)
    defer { fixture.remove() }
    let adapter = try OmniVoiceBatchTTSAdapter(configuration: fixture.configuration())

    do {
      _ = try await adapter.synthesize(fixture.request())
      Issue.record("Expected an output-size validation failure.")
    } catch let error as EvieTTSError {
      #expect(error == .outputMissing)
    }

    #expect(try fixture.requestDirectories().isEmpty)
  }

  @Test("times out and terminates the isolated child process group", arguments: [false, true])
  func timeout(observeResultLate: Bool) async throws {
    let fixture = try Fixture(script: Self.timedLongRunningScript)
    defer { fixture.remove() }
    try fixture.warmUpExecutable()
    let adapter = try OmniVoiceBatchTTSAdapter(
      configuration: fixture.configuration(timeout: 0.5, gracePeriod: 0.05)
    )
    let task = Task { try await adapter.synthesize(fixture.request()) }
    defer { task.cancel() }
    if observeResultLate {
      let timing = try await fixture.terminationTiming()
      try await fixture.expectChildStopped(timing.childIdentifier)
      // The consumer deliberately resumes after the process deadline. Only
      // the child-recorded clock can distinguish its lifetime from this delay.
      try await Task.sleep(for: .milliseconds(2_100))
    }
    do {
      _ = try await task.value
      Issue.record("Expected a timeout.")
    } catch let error as EvieTTSError {
      #expect(error == .timedOut)
    }
    let timing = try await fixture.terminationTiming()
    #expect(timing.lifetimeBeforeTermination < .seconds(2))
    let childIdentifier = try await fixture.recordedChildIdentifier()
    #expect(timing.childIdentifier == childIdentifier)
    try await fixture.expectChildStopped(childIdentifier)
    #expect(try fixture.requestDirectories().isEmpty)
  }

  @Test("task cancellation terminates the isolated child process group")
  func cancellation() async throws {
    let fixture = try Fixture(script: Self.longRunningScript)
    defer { fixture.remove() }
    let adapter = try OmniVoiceBatchTTSAdapter(
      configuration: fixture.configuration(timeout: 5, gracePeriod: 0.05)
    )
    let task = Task {
      try await adapter.synthesize(fixture.request())
    }

    let childIdentifier = try await fixture.recordedChildIdentifier()
    task.cancel()

    do {
      _ = try await task.value
      Issue.record("Expected cancellation.")
    } catch is CancellationError {
      // Expected.
    }
    try await fixture.expectChildStopped(childIdentifier)
    #expect(try fixture.requestDirectories().isEmpty)
  }

  @Test("rejects non-file executables without launching a process")
  func invalidExecutable() throws {
    let fixture = try Fixture(script: Self.successScript)
    defer { fixture.remove() }
    var configuration = fixture.configuration()
    configuration.executableURL = URL(string: "relative-helper")!

    #expect(throws: EvieTTSError.invalidConfiguration) {
      try OmniVoiceBatchTTSAdapter(configuration: configuration)
    }
  }

  @Test("rejects an offline cache without the tokenizer snapshot")
  func missingTokenizerSnapshot() throws {
    let fixture = try Fixture(script: Self.successScript)
    defer { fixture.remove() }
    let snapshotsURL = fixture.huggingFaceCacheURL
      .appendingPathComponent("hub", isDirectory: true)
      .appendingPathComponent(
        "models--eustlb--higgs-audio-v2-tokenizer",
        isDirectory: true
      )
      .appendingPathComponent("snapshots", isDirectory: true)
    try FileManager.default.removeItem(at: snapshotsURL)

    #expect(throws: EvieTTSError.invalidConfiguration) {
      try OmniVoiceBatchTTSAdapter(configuration: fixture.configuration())
    }
  }
}

