  /// The receipt comes from an actual SIGTERM handler in the process being
  /// timed, before waiting on its descendant. It cannot be synthesized by a
  /// delayed Swift continuation or mistaken for the warm-up process's receipt.
  fileprivate static let timedLongRunningScript = """
    #!/usr/bin/python3
    import json
    import os
    import signal
    import subprocess
    import sys
    import time
    from pathlib import Path

    arguments = dict(zip(sys.argv[1::2], sys.argv[2::2]))
    model = Path(arguments['--model'])
    started = time.monotonic_ns()
    child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(30)', str(model)])

    def terminated(signum, frame):
        receipt = {'startedNanoseconds': started,
                   'terminatedNanoseconds': time.monotonic_ns(),
                   'childIdentifier': child.pid}
        pending = model / 'termination.pending'
        pending.write_text(json.dumps(receipt))
        pending.replace(model / 'termination.json')
        # Process.terminate() used by warm-up signals only the parent. The
        # measured request must instead prove the runner signals its group.
        if model.name == 'warmup':
            try:
                os.kill(child.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        child.wait()
        sys.exit(128 + signum)

    signal.signal(signal.SIGTERM, terminated)
    signal.signal(signal.SIGINT, terminated)
    (model / 'child.pid').write_text(str(child.pid))
    while True:
        signal.pause()
    """

  fileprivate static let longRunningScript = """
    #!/bin/sh
    set -eu
    umask 077
    model_dir=''
    while [ "$#" -gt 0 ]; do
      key="$1"
      value="$2"
      shift 2
      case "$key" in
        --model) model_dir="$value" ;;
      esac
    done
    /bin/sleep 30 &
    child="$!"
    trap 'kill -TERM "$child" 2>/dev/null || true; wait "$child" 2>/dev/null || true; exit 143' TERM INT
    printf '%s' "$child" > "$model_dir/child.pid"
    wait "$child"
    """
}

private final class Fixture: @unchecked Sendable {
  let rootURL: URL
  let executableURL: URL
  let modelDirectoryURL: URL
  let huggingFaceCacheURL: URL
  let referenceAudioURL: URL
  let temporaryRootURL: URL

  init(script: String) throws {
    rootURL = FileManager.default.temporaryDirectory.appendingPathComponent(
      UUID().uuidString,
      isDirectory: true
    )
    executableURL = rootURL.appendingPathComponent("synthetic-omnivoice", isDirectory: false)
    modelDirectoryURL = rootURL.appendingPathComponent("model", isDirectory: true)
    huggingFaceCacheURL = rootURL.appendingPathComponent("huggingface", isDirectory: true)
    referenceAudioURL = rootURL.appendingPathComponent("reference.wav", isDirectory: false)
    temporaryRootURL =
      rootURL
      .appendingPathComponent("Evie", isDirectory: true)
      .appendingPathComponent("TTS", isDirectory: true)

    try FileManager.default.createDirectory(
      at: rootURL,
      withIntermediateDirectories: false,
      attributes: [.posixPermissions: NSNumber(value: 0o700)]
    )
    try FileManager.default.createDirectory(
      at: modelDirectoryURL,
      withIntermediateDirectories: false,
      attributes: [.posixPermissions: NSNumber(value: 0o700)]
    )
    try FileManager.default.createDirectory(
      at: huggingFaceCacheURL,
      withIntermediateDirectories: false,
      attributes: [.posixPermissions: NSNumber(value: 0o700)]
    )
    try FileManager.default.createDirectory(
      at:
        huggingFaceCacheURL
        .appendingPathComponent("hub", isDirectory: true)
        .appendingPathComponent(
          "models--eustlb--higgs-audio-v2-tokenizer",
          isDirectory: true
        )
        .appendingPathComponent("snapshots", isDirectory: true)
        .appendingPathComponent("synthetic", isDirectory: true),
      withIntermediateDirectories: true,
      attributes: [.posixPermissions: NSNumber(value: 0o700)]
    )
    try Data(script.utf8).write(to: executableURL)
    try FileManager.default.setAttributes(
      [.posixPermissions: NSNumber(value: 0o700)],
      ofItemAtPath: executableURL.path
    )
    try Data("synthetic-reference".utf8).write(to: referenceAudioURL)
    try FileManager.default.setAttributes(
      [.posixPermissions: NSNumber(value: 0o600)],
      ofItemAtPath: referenceAudioURL.path
    )
  }

  func remove() {
    stopOwnedDescendant(in: modelDirectoryURL)
    stopOwnedDescendant(in: rootURL.appendingPathComponent("warmup", isDirectory: true))
    try? FileManager.default.removeItem(at: rootURL)
  }

  /// Failure cleanup is restricted to a recorded PID whose live command still
  /// contains this fixture's unique directory and exact synthetic child code.
  private func stopOwnedDescendant(in directory: URL) {
    guard let data = try? Data(contentsOf: directory.appendingPathComponent("child.pid")),
      let identifier = Int32(String(decoding: data, as: UTF8.self)), identifier > 0
    else { return }
    let process = Process()
    let output = Pipe()
    process.executableURL = URL(fileURLWithPath: "/bin/ps")
    process.arguments = ["-o", "args=", "-p", String(identifier)]
    process.standardOutput = output
    process.standardError = FileHandle.nullDevice
    guard (try? process.run()) != nil else { return }
    process.waitUntilExit()
    let command = String(decoding: output.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
    guard command.contains(directory.path), command.contains("import time; time.sleep(30)") else {
      return
    }
    _ = kill(identifier, SIGKILL)
  }

  func configuration(
    timeout: TimeInterval = 2,
    gracePeriod: TimeInterval = 0.1
  ) -> OmniVoiceBatchTTSConfiguration {
    OmniVoiceBatchTTSConfiguration(
      executableURL: executableURL,
      modelDirectoryURL: modelDirectoryURL,
      huggingFaceCacheURL: huggingFaceCacheURL,
      temporaryRootURL: temporaryRootURL,
      timeout: timeout,
      terminationGracePeriod: gracePeriod
    )
  }

  func request() -> EvieTTSRequest {
    EvieTTSRequest(
      text: "PRIVATE-TEXT-SENTINEL",
      voiceReference: EvieTTSVoiceReference(
        audioFileURL: referenceAudioURL,
        transcript: "PRIVATE-REFERENCE-SENTINEL"
      )
    )
  }

  func permissions(at url: URL) throws -> Int {
    let attributes = try FileManager.default.attributesOfItem(atPath: url.path)
    return (attributes[.posixPermissions] as? NSNumber)?.intValue ?? -1
  }

  func requestDirectories() throws -> [URL] {
    guard FileManager.default.fileExists(atPath: temporaryRootURL.path) else { return [] }
    return try FileManager.default.contentsOfDirectory(
      at: temporaryRootURL,
      includingPropertiesForKeys: [.isDirectoryKey]
    )
  }

  /// Launches the script once and stops it again, before anything is timed.
  ///
  /// macOS charges the first execution of a file it has never seen a provenance
  /// check that the second execution of the same file does not pay. Measured on
  /// this machine, 200 launches of freshly written copies of the long-running
  /// script took 29 ms to reach the line that records the descendant's pid at
  /// the median, 324 ms at the 99th percentile and 450 ms at the worst, while
  /// 200 launches of one already-executed file never exceeded 41 ms. The timeout
  /// test gives the child 500 ms before killing its process group, so that tail
  /// fell on the wrong side of the deadline in about two runs per hundred: the
  /// script died before writing the pid file and the test failed reading it,
  /// which looked like a flaky adapter and was only a cold file. Paying the
  /// check before the clock starts puts the deadline back on the timeout.
  func warmUpExecutable() throws {
    let directory = rootURL.appendingPathComponent("warmup", isDirectory: true)
    try FileManager.default.createDirectory(
      at: directory,
      withIntermediateDirectories: false,
      attributes: [.posixPermissions: NSNumber(value: 0o700)]
    )
    let process = Process()
    process.executableURL = executableURL
    process.arguments = [
      "--model", directory.path,
      "--test_list", "/dev/stdin",
      "--res_dir", directory.path,
      "--nj_per_gpu", "1",
      "--batch_size", "1",
      "--warmup", "0",
      "--num_step", "32",
    ]
    process.standardInput = FileHandle.nullDevice
    process.standardOutput = FileHandle.nullDevice
    process.standardError = FileHandle.nullDevice
    try process.run()

    // Waiting for the pid file rather than for the launch, because the cost
    // being paid here covers the whole path the timed run has to walk: the
    // exec, the shell, and the fork of the descendant.
    let pidFileURL = directory.appendingPathComponent("child.pid", isDirectory: false)
    for _ in 0..<200 {
      if FileManager.default.fileExists(atPath: pidFileURL.path) {
        break
      }
      Thread.sleep(forTimeInterval: 0.005)
    }
    process.terminate()
    process.waitUntilExit()
  }

  struct TerminationTiming: Decodable {
    let startedNanoseconds: UInt64
    let terminatedNanoseconds: UInt64
    let childIdentifier: Int32
    var lifetimeBeforeTermination: Duration {
      .nanoseconds(Int64(terminatedNanoseconds - startedNanoseconds))
    }
  }

  func terminationTiming() async throws -> TerminationTiming {
    let file = modelDirectoryURL.appendingPathComponent("termination.json")
    let deadline = ContinuousClock.now + .seconds(2)
    while true {
      // Check the actual receipt before the observer's deadline: its executor
      // can resume late even though SIGTERM was delivered on time.
      if let data = try? Data(contentsOf: file) {
        let timing = try JSONDecoder().decode(TerminationTiming.self, from: data)
        guard timing.childIdentifier > 0,
          timing.terminatedNanoseconds >= timing.startedNanoseconds,
          timing.terminatedNanoseconds - timing.startedNanoseconds <= UInt64(Int64.max)
        else { throw FixtureError.invalidTerminationTiming }
        return timing
      }
      guard ContinuousClock.now < deadline else { throw FixtureError.terminationTimingMissing }
      try await Task.sleep(for: .milliseconds(10))
    }
  }

  func recordedChildIdentifier() async throws -> Int32 {
    let pidFileURL = modelDirectoryURL.appendingPathComponent("child.pid", isDirectory: false)
    for _ in 0..<40 {
      if let data = try? Data(contentsOf: pidFileURL),
        let value = Int32(String(decoding: data, as: UTF8.self))
      {
        return value
      }
      try await Task.sleep(for: .milliseconds(25))
    }
    throw FixtureError.childIdentifierMissing
  }

  func expectChildStopped(_ processIdentifier: Int32) async throws {
    for _ in 0..<80 {
      let state = try processState(processIdentifier)
      if state == nil || state == "Z" {
        return
      }
      try await Task.sleep(for: .milliseconds(25))
    }
    Issue.record("The synthetic descendant remained active after process-group termination.")
  }

  private func processState(_ processIdentifier: Int32) throws -> Character? {
    let process = Process()
    let output = Pipe()
    process.executableURL = URL(fileURLWithPath: "/bin/ps")
    process.arguments = ["-o", "state=", "-p", String(processIdentifier)]
    process.standardOutput = output
    process.standardError = FileHandle.nullDevice
    try process.run()
    process.waitUntilExit()
    let value = String(
      decoding: output.fileHandleForReading.readDataToEndOfFile(),
      as: UTF8.self
    ).trimmingCharacters(in: .whitespacesAndNewlines)
    return value.first
  }
}

private enum FixtureError: Error {
  case terminationTimingMissing
  case invalidTerminationTiming
  case childIdentifierMissing
}
